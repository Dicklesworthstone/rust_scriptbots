#[derive(Parser, Debug)]
#[command(
    name = "scriptbots-control",
    version,
    about = "Interact with ScriptBots runtime controls via REST"
)]
struct Cli {
    /// Base URL for the running ScriptBots REST control API.
    #[arg(
        long,
        env = "SCRIPTBOTS_CONTROL_URL",
        default_value = "http://127.0.0.1:8088"
    )]
    base_url: String,

    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// List all available configuration knobs and their current values.
    List,
    /// Fetch the complete configuration snapshot as JSON.
    Get,
    /// Update a configuration knob by path.
    Set {
        /// Dot-delimited knob path (e.g. world_width or neuroflow.enabled).
        path: String,
        /// New value expressed as JSON (unquoted literal, or a raw string fallback).
        value: String,
    },
    /// Apply a JSON patch object to the configuration.
    Patch {
        /// Optional file to read the JSON patch from; if omitted, read from the CLI arguments.
        #[arg(short, long)]
        file: Option<PathBuf>,
        /// Inline JSON (joined with spaces) when --file is not supplied.
        json: Vec<String>,
    },
    /// Launch an updating TUI dashboard to monitor knobs.
    Watch {
        /// Refresh interval in milliseconds.
        #[arg(long, default_value_t = 500)]
        interval_ms: u64,
    },
    /// Export recent metrics or tick records to CSV from a FrankenSQLite run.
    Export {
        /// Kind of dataset to export.
        #[arg(value_enum)]
        kind: ExportKind,
        /// Path to the SQLite database file generated by the simulation.
        #[arg(long = "db", value_name = "FILE")]
        database: PathBuf,
        /// Destination CSV file path (directories created as needed).
        #[arg(long, value_name = "FILE")]
        out: PathBuf,
        /// Limit to the most recent N rows (oldest-first in the output). Omit for full export.
        #[arg(long, value_name = "ROWS")]
        last: Option<usize>,
    },
    /// List available scenario presets.
    Presets,
    /// Apply a preset by name via REST.
    ApplyPreset {
        /// Preset name to apply (see `presets`).
        name: String,
    },
    /// Request a one-off ASCII or PNG screenshot from the running app via REST.
    Screenshot {
        /// Output path for the screenshot; for PNG, must end with .png; otherwise ASCII .txt.
        #[arg(long, value_name = "FILE")]
        out: PathBuf,
        /// PNG image export (GUI renderer view). When false, writes ASCII map snapshot.
        #[arg(long = "png", default_value_t = false)]
        png: bool,
    },
    /// Show hydrology metrics and raw layers.
    Hydrology,
}

#[derive(Copy, Clone, Debug, ValueEnum)]
enum ExportKind {
    Metrics,
    Ticks,
}

#[tokio::main]
async fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Export {
            kind,
            database,
            out,
            last,
        } => export_command(kind, database, out, last)?,
        other => {
            let client = Client::builder()
                .build()
                .context("failed to build HTTP client")?;
            match other {
                Command::List => list_command(&client, &cli.base_url).await?,
                Command::Get => get_command(&client, &cli.base_url).await?,
                Command::Set { path, value } => {
                    set_command(&client, &cli.base_url, path, value).await?
                }
                Command::Patch { file, json } => {
                    patch_command(&client, &cli.base_url, file, json).await?
                }
                Command::Watch { interval_ms } => {
                    run_watch(
                        client.clone(),
                        cli.base_url.clone(),
                        Duration::from_millis(interval_ms),
                    )
                    .await?
                }
                Command::Export { .. } => unreachable!("handled in outer match"),
                Command::Presets => presets_list(&client, &cli.base_url).await?,
                Command::ApplyPreset { name } => {
                    presets_apply(&client, &cli.base_url, &name).await?
                }
                Command::Screenshot { out, png } => {
                    screenshot_request(&client, &cli.base_url, out, png).await?
                }
                Command::Hydrology => hydrology_command(&client, &cli.base_url).await?,
            }
        }
    }

    Ok(())
}

fn export_command(
    kind: ExportKind,
    database: PathBuf,
    out: PathBuf,
    last: Option<usize>,
) -> Result<()> {
    if let Some(limit) = last
        && limit == 0
    {
        bail!("--last must be greater than zero when provided");
    }

    if let Some(parent) = out.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create export directory {}", parent.display()))?;
    }

    let database_path = database.to_str().with_context(|| {
        format!(
            "FrankenSQLite database path is not valid UTF-8: {}",
            database.display()
        )
    })?;
    let storage = StorageReader::open(database_path).with_context(|| {
        format!(
            "failed to open FrankenSQLite database {}",
            database.display()
        )
    })?;

    let export_result = (|| -> Result<(usize, Vec<u8>)> {
        // Finish every database read and CSV serialization before publishing the requested path.
        // A query/encoding failure therefore cannot leave an empty final-name export behind.
        let mut writer = Writer::from_writer(Vec::new());

        let written = match kind {
            ExportKind::Metrics => export_metrics(&storage, &mut writer, last)?,
            ExportKind::Ticks => export_ticks(&storage, &mut writer, last)?,
        };

        writer.flush().context("failed to flush CSV writer")?;
        let bytes = writer
            .into_inner()
            .map_err(|error| anyhow::anyhow!("failed to finalize CSV buffer: {error}"))?;
        Ok((written, bytes))
    })();
    let close_result = storage.close().with_context(|| {
        format!(
            "failed to close FrankenSQLite database {}",
            database.display()
        )
    });
    let (written, bytes) = export_result?;
    close_result?;
    let mut file = open_distinct_export_destination(&database, &out)?;
    file.write_all(&bytes)
        .with_context(|| format!("failed to write export file {}", out.display()))?;
    file.sync_all()
        .with_context(|| format!("failed to sync export file {}", out.display()))?;
    println!(
        "{} {} rows from {} to {}",
        "exported".green().bold(),
        written,
        format!("{:?}", kind).cyan(),
        out.display()
    );

    Ok(())
}

fn open_distinct_export_destination(database: &Path, out: &Path) -> Result<fs::File> {
    let canonical_database = fs::canonicalize(database).with_context(|| {
        format!(
            "failed to resolve FrankenSQLite database {} before export",
            database.display()
        )
    })?;
    let canonical_out = resolve_export_destination(out)?;
    if canonical_database == canonical_out
        || is_database_sidecar(&canonical_database, &canonical_out)
    {
        bail!(
            "refusing to export CSV to {} because --out refers to the FrankenSQLite database {} or one of its live sidecars",
            out.display(),
            database.display()
        );
    }

    let file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(out)
        .map_err(|error| {
            if error.kind() == io::ErrorKind::AlreadyExists {
                anyhow::anyhow!(
                    "refusing to export CSV to {} because --out already exists; exports require a new path so no database, sidecar, hard link, symbolic link, or prior export can be overwritten",
                    out.display()
                )
            } else {
                anyhow::Error::new(error)
                    .context(format!("failed to create export file {}", out.display()))
            }
        })?;
    Ok(file)
}

fn resolve_export_destination(out: &Path) -> Result<PathBuf> {
    if out.exists() {
        return fs::canonicalize(out).with_context(|| {
            format!(
                "failed to resolve existing export destination {}",
                out.display()
            )
        });
    }

    let parent = out.parent().filter(|path| !path.as_os_str().is_empty());
    let canonical_parent = match parent {
        Some(parent) => fs::canonicalize(parent)
            .with_context(|| format!("failed to resolve export directory {}", parent.display()))?,
        None => std::env::current_dir().context("failed to resolve current export directory")?,
    };
    let file_name = out
        .file_name()
        .with_context(|| format!("export destination {} has no file name", out.display()))?;
    Ok(canonical_parent.join(file_name))
}

fn is_database_sidecar(database: &Path, out: &Path) -> bool {
    STORAGE_SIDECAR_SUFFIXES.into_iter().any(|suffix| {
        let mut sidecar = database.as_os_str().to_os_string();
        sidecar.push(suffix);
        paths_equal_for_platform(out.as_os_str(), sidecar.as_os_str())
    })
}

fn paths_equal_for_platform(left: &std::ffi::OsStr, right: &std::ffi::OsStr) -> bool {
    #[cfg(windows)]
    {
        // Canonicalization cannot resolve a destination that does not exist yet. Fold the full
        // planned path before create-new so case variants cannot claim a live SQLite sidecar on
        // Windows' default case-insensitive filesystems. Lossy conversion can only make this
        // guard more conservative for malformed UTF-16 names.
        left.to_string_lossy().to_lowercase() == right.to_string_lossy().to_lowercase()
    }
    #[cfg(not(windows))]
    {
        left == right
    }
}

fn export_metrics<W: Write>(
    storage: &StorageReader,
    writer: &mut Writer<W>,
    last: Option<usize>,
) -> Result<usize> {
    let records = storage.recent_metrics(last)?;

    writer
        .write_record(["tick", "name", "value"])
        .context("failed to write metrics header")?;
    for record in &records {
        writer.write_record([
            record.tick.to_string(),
            record.name.clone(),
            format!("{:.6}", record.value),
        ])?;
    }

    Ok(records.len())
}

fn export_ticks<W: Write>(
    storage: &StorageReader,
    writer: &mut Writer<W>,
    last: Option<usize>,
) -> Result<usize> {
    let records = storage.recent_ticks(last)?;

    writer
        .write_record([
            "tick",
            "epoch",
            "closed",
            "agent_count",
            "births",
            "deaths",
            "total_energy",
            "average_energy",
            "average_health",
        ])
        .context("failed to write tick header")?;
    for record in &records {
        writer.write_record([
            record.tick.to_string(),
            record.epoch.to_string(),
            record.closed.to_string(),
            record.agent_count.to_string(),
            record.births.to_string(),
            record.deaths.to_string(),
            format!("{:.6}", record.total_energy),
            format!("{:.6}", record.average_energy),
            format!("{:.6}", record.average_health),
        ])?;
    }

    Ok(records.len())
}

async fn list_command(client: &Client, base_url: &str) -> Result<()> {
    let knobs: Vec<KnobEntry> = fetch_knobs(client, base_url).await?;
    if knobs.is_empty() {
        println!("{}", "No knobs reported by the control API".yellow());
        return Ok(());
    }

    let mut knobs = knobs;
    knobs.sort_by(|a, b| a.path.cmp(&b.path));

    println!(
        "{:<54} {:<10} {}",
        "PATH".bold().cyan(),
        "TYPE".bold().cyan(),
        "VALUE".bold().cyan()
    );
    println!("{}", "-".repeat(96).dimmed());

    for entry in knobs {
        println!(
            "{:<54} {:<10} {}",
            entry.path.bold(),
            knob_kind_label(entry.kind).italic().blue(),
            value_to_string(&entry.value, 32)
        );
    }

    Ok(())
}

async fn get_command(client: &Client, base_url: &str) -> Result<()> {
    let snapshot: ConfigSnapshot = fetch_config(client, base_url).await?;
    let pretty = serde_json::to_string_pretty(&snapshot.config)
        .context("failed to format configuration JSON")?;
    println!("{} {}", "tick".green().bold(), snapshot.tick);
    println!("{}", pretty.cyan());
    Ok(())
}

async fn set_command(
    client: &Client,
    base_url: &str,
    path: String,
    raw_value: String,
) -> Result<()> {
    let value = parse_value(&raw_value)?;
    let request = KnobApplyRequest {
        updates: vec![KnobUpdate {
            path: path.clone(),
            value: value.clone(),
        }],
    };
    let snapshot: ConfigSnapshot = apply_updates(client, base_url, &request).await?;
    let resolved = snapshot
        .config
        .pointer(&json_pointer(&path))
        .cloned()
        .unwrap_or(Value::Null);
    println!(
        "{} {} => {}",
        "updated".green().bold(),
        path,
        value_to_string(&resolved, 48)
    );
    Ok(())
}

async fn patch_command(
    client: &Client,
    base_url: &str,
    file: Option<PathBuf>,
    inline: Vec<String>,
) -> Result<()> {
    let patch_value = if let Some(path) = file {
        let data = std::fs::read_to_string(&path)
            .with_context(|| format!("failed to read patch file {}", path.display()))?;
        serde_json::from_str::<Value>(&data)
            .with_context(|| format!("patch file {} did not contain valid JSON", path.display()))?
    } else {
        let joined = inline.join(" ");
        if joined.trim().is_empty() {
            bail!("provide either --file or inline JSON patch arguments");
        }
        serde_json::from_str::<Value>(&joined)
            .context("inline patch arguments were not valid JSON")?
    };

    if !patch_value.is_object() {
        bail!("patch payload must be a JSON object");
    }

    let body = ConfigPatchRequest { patch: patch_value };
    let snapshot: ConfigSnapshot = apply_patch(client, base_url, &body).await?;
    println!("{}", "Configuration patch applied".green().bold());
    println!("tick {}", snapshot.tick);
    Ok(())
}

async fn run_watch(client: Client, base_url: String, interval: Duration) -> Result<()> {
    tokio::task::spawn_blocking(move || watch_blocking(client, base_url, interval)).await??;
    Ok(())
}

fn watch_blocking(client: Client, base_url: String, interval: Duration) -> Result<()> {
    enable_raw_mode().context("failed to enable raw mode")?;
    let mut stdout = io::stdout();
    execute!(stdout, EnterAlternateScreen, Hide).context("failed to enter alternate screen")?;
    let backend = CrosstermBackend::new(stdout);
    let mut terminal = Terminal::new(backend).context("failed to create terminal")?;
    let _cleanup = TerminalCleanup;

    let handle = tokio::runtime::Handle::current();
    let mut previous: HashMap<String, Value> = HashMap::new();
    let mut rows: Vec<WatchRow> = Vec::new();
    let mut last_error: Option<String> = None;
    let mut last_refresh: Option<Instant> = None;

    loop {
        if last_refresh.is_none_or(|at| at.elapsed() >= interval) {
            match handle.block_on(fetch_knobs(&client, &base_url)) {
                Ok(entries) => {
                    rows = build_rows(&entries, &previous);
                    previous = entries
                        .into_iter()
                        .map(|entry| (entry.path, entry.value))
                        .collect();
                    last_error = None;
                }
                Err(err) => {
                    last_error = Some(err.to_string());
                }
            }
            last_refresh = Some(Instant::now());
        }

        terminal
            .draw(|frame| draw_watch(frame, &rows, last_error.as_deref(), interval))
            .context("failed to draw watch UI")?;

        let event_ready =
            event::poll(Duration::from_millis(100)).context("failed to poll terminal events")?;
        if event_ready
            && let Event::Key(key) = event::read().context("failed to read terminal event")?
            && key.kind == KeyEventKind::Press
        {
            match key.code {
                KeyCode::Char('q') | KeyCode::Esc => break,
                KeyCode::Char('r') => {
                    // Force refresh on demand.
                    last_refresh = None;
                }
                _ => {}
            }
        }
    }

    terminal.show_cursor().ok();
    Ok(())
}

fn build_rows(entries: &[KnobEntry], previous: &HashMap<String, Value>) -> Vec<WatchRow> {
    let mut rows = Vec::with_capacity(entries.len());
    for entry in entries {
        let changed = previous
            .get(&entry.path)
            .map(|value| value != &entry.value)
            .unwrap_or(true);
        rows.push(WatchRow {
            path: entry.path.clone(),
            kind: entry.kind.clone(),
            value: entry.value.clone(),
            changed,
        });
    }
    rows.sort_by(|a, b| a.path.cmp(&b.path));
    rows
}

fn draw_watch(frame: &mut Frame<'_>, rows: &[WatchRow], error: Option<&str>, interval: Duration) {
    let layout = Layout::default()
        .direction(Direction::Vertical)
        .constraints([Constraint::Length(3), Constraint::Min(1)])
        .split(frame.area());

    let mut header_lines = vec![
        Line::from(vec![
            Span::styled(
                "ScriptBots Control Dashboard ",
                Style::default()
                    .fg(Color::Cyan)
                    .add_modifier(Modifier::BOLD),
            ),
            Span::raw("(press 'q' to quit, 'r' to refresh)"),
        ]),
        Line::from(Span::styled(
            format!("Refresh interval: {} ms", interval.as_millis()),
            Style::default().fg(Color::Gray),
        )),
    ];

    if let Some(message) = error {
        header_lines.push(Line::from(Span::styled(
            format!("Last error: {message}"),
            Style::default().fg(Color::Red),
        )));
    }

    let header = Paragraph::new(header_lines).block(Block::default().borders(Borders::ALL));
    frame.render_widget(header, layout[0]);

    if rows.is_empty() {
        let empty = Paragraph::new("Waiting for knob data...")
            .block(Block::default().borders(Borders::ALL));
        frame.render_widget(empty, layout[1]);
        return;
    }

    let table_rows: Vec<Row> = rows
        .iter()
        .map(|row| {
            let style = if row.changed {
                Style::default()
                    .fg(Color::Yellow)
                    .add_modifier(Modifier::BOLD)
            } else {
                Style::default()
            };
            Row::new(vec![
                Span::styled(&row.path, style),
                Span::styled(
                    knob_kind_label(row.kind.clone()),
                    Style::default()
                        .fg(Color::Blue)
                        .add_modifier(Modifier::ITALIC),
                ),
                Span::styled(value_to_string(&row.value, 40), style),
            ])
        })
        .collect();

    let table = Table::new(
        table_rows,
        [
            Constraint::Percentage(45),
            Constraint::Length(12),
            Constraint::Percentage(43),
        ],
    )
    .header(Row::new(vec![
        Span::styled(
            "PATH",
            Style::default()
                .fg(Color::Cyan)
                .add_modifier(Modifier::BOLD),
        ),
        Span::styled(
            "TYPE",
            Style::default()
                .fg(Color::Cyan)
                .add_modifier(Modifier::BOLD),
        ),
        Span::styled(
            "VALUE",
            Style::default()
                .fg(Color::Cyan)
                .add_modifier(Modifier::BOLD),
        ),
    ]))
    .block(Block::default().borders(Borders::ALL))
    .column_spacing(2);

    frame.render_widget(table, layout[1]);
}

struct TerminalCleanup;

impl Drop for TerminalCleanup {
    fn drop(&mut self) {
        let _ = disable_raw_mode();
        let mut stdout = io::stdout();
        let _ = execute!(stdout, LeaveAlternateScreen, Show);
    }
}

#[derive(Clone)]
struct WatchRow {
    path: String,
    kind: KnobKind,
    value: Value,
    changed: bool,
}

async fn fetch_knobs(client: &Client, base_url: &str) -> Result<Vec<KnobEntry>> {
    let url = join_url(base_url, "/api/knobs");
    let response = client
        .get(url)
        .send()
        .await
        .context("failed to fetch knob list")?;
    parse_response(response).await
}

async fn fetch_config(client: &Client, base_url: &str) -> Result<ConfigSnapshot> {
    let url = join_url(base_url, "/api/config");
    let response = client
        .get(url)
        .send()
        .await
        .context("failed to fetch configuration")?;
    parse_response(response).await
}

async fn apply_updates(
    client: &Client,
    base_url: &str,
    request: &KnobApplyRequest,
) -> Result<ConfigSnapshot> {
    let url = join_url(base_url, "/api/knobs/apply");
    let response = client
        .post(url)
        .json(request)
        .send()
        .await
        .context("failed to apply knob updates")?;
    parse_response(response).await
}

async fn apply_patch(
    client: &Client,
    base_url: &str,
    request: &ConfigPatchRequest,
) -> Result<ConfigSnapshot> {
    let url = join_url(base_url, "/api/config");
    let response = client
        .patch(url)
        .json(request)
        .send()
        .await
        .context("failed to apply configuration patch")?;
    parse_response(response).await
}

async fn parse_response<T>(response: reqwest::Response) -> Result<T>
where
    T: DeserializeOwned,
{
    let status = response.status();
    if status.is_success() {
        response
            .json::<T>()
            .await
            .context("failed to deserialize control API response")
    } else {
        let body = response.text().await.unwrap_or("<unavailable>".to_string());
        bail!("control API request failed ({status}): {body}");
    }
}

async fn presets_list(client: &Client, base_url: &str) -> Result<()> {
    #[derive(serde::Deserialize)]
    struct PresetList {
        presets: Vec<String>,
    }
    let url = join_url(base_url, "/api/presets");
    let list: PresetList = client.get(url).send().await?.json().await?;
    if list.presets.is_empty() {
        println!("No presets available");
    } else {
        println!("Available presets:");
        for name in list.presets {
            println!("  - {}", name);
        }
    }
    Ok(())
}

async fn presets_apply(client: &Client, base_url: &str, name: &str) -> Result<()> {
    #[derive(serde::Serialize)]
    struct Apply {
        name: String,
    }
    let url = join_url(base_url, "/api/presets/apply");
    let body = Apply {
        name: name.to_string(),
    };
    let snapshot: ConfigSnapshot = client.post(url).json(&body).send().await?.json().await?;
    println!("Applied preset '{}' at tick {}", name, snapshot.tick);
    Ok(())
}

async fn screenshot_request(
    client: &Client,
    base_url: &str,
    out: PathBuf,
    png: bool,
) -> Result<()> {
    let url = if png {
        join_url(base_url, "/api/screenshot/png")
    } else {
        join_url(base_url, "/api/screenshot/ascii")
    };

    let resp = client.get(url).send().await?;
    if !resp.status().is_success() {
        let body = resp.text().await.unwrap_or_default();
        bail!("screenshot request failed: {}", body);
    }

    let bytes = resp.bytes().await?;
    if let Some(parent) = out.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(&out, &bytes)?;
    println!("Saved screenshot to {}", out.display());
    Ok(())
}

async fn hydrology_command(client: &Client, base_url: &str) -> Result<()> {
    let url = join_url(base_url, "/api/hydrology");
    let response = client
        .get(&url)
        .send()
        .await
        .with_context(|| format!("failed to GET hydrology snapshot from {url}"))?;

    if response.status() == StatusCode::NOT_FOUND {
        println!(
            "{} hydrology state is not yet available.",
            "info".yellow().bold()
        );
        return Ok(());
    }

    let status = response.status();
    let response = response
        .error_for_status()
        .with_context(|| format!("request to {url} failed with status {status}"))?;

    let snapshot: HydrologySnapshot = response
        .json()
        .await
        .context("failed to decode hydrology snapshot")?;

    let total_cells = (snapshot.width as f64) * (snapshot.height as f64);
    let shallow_ratio = if total_cells > 0.0 {
        snapshot.flooded_shallow_count as f64 / total_cells
    } else {
        0.0
    };
    let deep_ratio = if total_cells > 0.0 {
        snapshot.flooded_deep_count as f64 / total_cells
    } else {
        0.0
    };

    println!(
        "{} hydrology grid {}×{}",
        "Hydrology".green().bold(),
        snapshot.width,
        snapshot.height
    );
    println!(
        "  total depth: {:.4} | mean depth: {:.4}",
        snapshot.total_water_depth, snapshot.mean_water_depth
    );
    println!(
        "  flooded: shallow {} ({:.1}%, ≥{:.2}), deep {} ({:.1}%, ≥{:.2})",
        snapshot.flooded_shallow_count,
        shallow_ratio * 100.0,
        snapshot.shallow_threshold,
        snapshot.flooded_deep_count,
        deep_ratio * 100.0,
        snapshot.deep_threshold
    );
    println!(
        "  arrays: water_depth {}, flow_dirs {}, basins {}, accumulation {}",
        snapshot.water_depth.len(),
        snapshot.flow_directions.len(),
        snapshot.basin_ids.len(),
        snapshot.accumulation.len()
    );

    Ok(())
}

fn join_url(base: &str, path: &str) -> String {
    let base = base.trim_end_matches('/');
    if path.starts_with('/') {
        format!("{base}{path}")
    } else {
        format!("{base}/{path}")
    }
}

fn parse_value(raw: &str) -> Result<Value> {
    match serde_json::from_str::<Value>(raw) {
        Ok(value) => Ok(value),
        Err(_) => Ok(Value::String(raw.to_string())),
    }
}

fn knob_kind_label(kind: KnobKind) -> &'static str {
    match kind {
        KnobKind::Number => "number",
        KnobKind::Integer => "integer",
        KnobKind::Boolean => "bool",
        KnobKind::String => "string",
        KnobKind::Array => "array",
        KnobKind::Object => "object",
        KnobKind::Null => "null",
    }
}

fn value_to_string(value: &Value, max_len: usize) -> String {
    let raw = match value {
        Value::String(s) => format!("\"{}\"", s),
        other => serde_json::to_string(other).unwrap_or_else(|_| "<error>".to_string()),
    };
    if max_len == 0 {
        return String::new();
    }

    if raw.chars().count() <= max_len {
        return raw;
    }

    let mut truncated: String = raw.chars().take(max_len.saturating_sub(1)).collect();
    truncated.push('…');
    truncated
}

fn json_pointer(path: &str) -> String {
    let mut pointer = String::from("/");
    pointer.push_str(&path.replace('.', "/"));
    pointer
}

