#!/usr/bin/env bash
# Produce the browser package for bd-azi3; execute through a pinned DSR profile.
set -euo pipefail
set -o noclobber

fail() {
  printf 'wasm-package: %s\n' "$1" >&2
  exit 1
}

[[ "$#" -eq 1 ]] || fail "usage: bash scripts/package_wasm.sh /absolute/fresh/package-directory"
[[ "$1" = /* ]] || fail "output directory must be absolute"
command -v wasm-pack >/dev/null 2>&1 || fail "the DSR toolchain must provide wasm-pack 0.15.0"
command -v jq >/dev/null 2>&1 || fail "jq is required"
[[ "$(wasm-pack --version)" == "wasm-pack 0.15.0" ]] || fail "expected pinned wasm-pack 0.15.0"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo_root="$(cd "$script_dir/.." && pwd -P)"
package_parent="$(cd "$(dirname "$1")" && pwd -P)"
package_name="$(basename "$1")"
[[ "$package_name" != . && "$package_name" != .. ]] || fail "output must name a fresh directory"
package_dir="$package_parent/$package_name"
generated_dir="$package_dir.wasm-pack"
[[ ! -e "$package_dir" && ! -L "$package_dir" ]] || fail "package output already exists: $package_dir"
[[ ! -e "$generated_dir" && ! -L "$generated_dir" ]] || fail "generated output already exists: $generated_dir"
mkdir -- "$package_dir" "$generated_dir"

cd "$repo_root"
wasm-pack build crates/scriptbots-web --target web --out-dir "$generated_dir" -- --locked

generated_manifest="$generated_dir/package.json"
jq -e '
  def filename: type == "string" and length > 0 and test("^[A-Za-z0-9_][A-Za-z0-9_.-]*$");
  (.name | type == "string" and length > 0)
  and (.version | type == "string" and length > 0)
  and .type == "module"
  and ((.module // .main) | filename)
  and (.types | filename)
  and (.files | type == "array" and all(.[]; filename))
  and (.files | map(select(endswith(".wasm"))) | length == 1)
' "$generated_manifest" >/dev/null
module_file="$(jq -r '.module // .main' "$generated_manifest")"
types_file="$(jq -r '.types' "$generated_manifest")"
wasm_file="$(jq -r '.files[] | select(endswith(".wasm"))' "$generated_manifest")"
jq -e --arg module "$module_file" --arg types "$types_file" '
  (.files | index($module) != null) and (.files | index($types) != null)
' "$generated_manifest" >/dev/null
while IFS= read -r artifact; do
  [[ -f "$generated_dir/$artifact" && ! -L "$generated_dir/$artifact" && -s "$generated_dir/$artifact" ]] \
    || fail "missing or invalid generated package file: $artifact"
done < <(jq -r '.files[]' "$generated_manifest")

# Preserve the original manifest and all generated bytes in the fresh sibling.
# Only the final package's new metadata receives the standard export map.
shopt -s dotglob nullglob
for artifact in "$generated_dir"/*; do
  [[ "$(basename "$artifact")" == package.json ]] && continue
  cp -a -- "$artifact" "$package_dir/"
done
for notice in LICENSE THIRD-PARTY-LICENSES.md; do
  if [[ -e "$package_dir/$notice" ]]; then
    cmp -- "$repo_root/$notice" "$package_dir/$notice" \
      || fail "generated notice differs from the repository: $notice"
  else
    cp -- "$repo_root/$notice" "$package_dir/$notice"
  fi
done
jq --arg module "./$module_file" --arg types "./$types_file" --arg wasm "./$wasm_file" '
  .exports = {
    ".": {types: $types, import: $module, default: $module},
    "./package.json": "./package.json",
    ($wasm): $wasm
  }
  | .files = ((.files + ["LICENSE", "THIRD-PARTY-LICENSES.md"]) | unique)
' "$generated_manifest" > "$package_dir/package.json"
for artifact in "$module_file" "$types_file" "$wasm_file"; do
  cmp -- "$generated_dir/$artifact" "$package_dir/$artifact"
done
printf 'wasm-package: package=%s original-manifest=%s\n' "$package_dir" "$generated_manifest"
